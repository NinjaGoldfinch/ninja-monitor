//! `--init`: writes a starting config from the services running on this
//! machine, so a first install needs no hand editing.

use std::fmt::Write;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

use crate::sampler::cgroup::{parse_keyed_u64, parse_single_u64};
use crate::sampler::host::parse_meminfo;

/// Units that come with the OS and are not worth watching individually.
const SYSTEM_UNITS: &[&str] = &[
    "accounts-daemon",
    "apport",
    "atd",
    "avahi-daemon",
    "chrony",
    "chronyd",
    "cron",
    "dbus",
    "dbus-broker",
    "fwupd",
    "irqbalance",
    "ModemManager",
    "multipathd",
    "networkd-dispatcher",
    "NetworkManager",
    "ninja-monitor",
    "packagekit",
    "polkit",
    "qemu-guest-agent",
    "rsyslog",
    "snapd",
    "ssh",
    "sshd",
    "thermald",
    "udisks2",
    "unattended-upgrades",
    "upower",
    "wpa_supplicant",
];

const SYSTEM_PREFIXES: &[&str] = &[
    "systemd-",
    "getty@",
    "serial-getty@",
    "user@",
    "user-runtime-dir@",
    "cloud-",
    "snap.",
    "lxd",
];

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Detected {
    pub unit: String,
    pub anon_bytes: Option<u64>,
    pub paths: Vec<PathBuf>,
}

impl Detected {
    pub fn name(&self) -> &str {
        self.unit.strip_suffix(".service").unwrap_or(&self.unit)
    }
}

pub fn is_system_unit(unit: &str) -> bool {
    let name = unit.strip_suffix(".service").unwrap_or(unit);
    SYSTEM_UNITS.contains(&name) || SYSTEM_PREFIXES.iter().any(|p| name.starts_with(p))
}

/// Running, non-OS services under `system.slice`, biggest anonymous memory first.
/// `state_paths` maps a unit to its data directories.
pub fn detect(cgroup_root: &Path, state_paths: impl Fn(&str) -> Vec<PathBuf>) -> Vec<Detected> {
    let Ok(entries) = fs::read_dir(cgroup_root.join("system.slice")) else {
        return Vec::new();
    };
    let mut found: Vec<Detected> = entries
        .filter_map(Result::ok)
        .filter_map(|entry| {
            let unit = entry.file_name().into_string().ok()?;
            if !unit.ends_with(".service") || is_system_unit(&unit) {
                return None;
            }
            let dir = entry.path();
            let pids = fs::read_to_string(dir.join("pids.current"))
                .ok()
                .and_then(|t| parse_single_u64(&t));
            let running = match pids {
                Some(n) => n > 0,
                None => {
                    fs::read_to_string(dir.join("cgroup.procs")).is_ok_and(|t| !t.trim().is_empty())
                }
            };
            if !running {
                return None;
            }
            let anon_bytes = fs::read_to_string(dir.join("memory.stat"))
                .ok()
                .and_then(|t| parse_keyed_u64(&t, "anon"));
            let paths = state_paths(&unit);
            Some(Detected {
                unit,
                anon_bytes,
                paths,
            })
        })
        .collect();
    found.sort_by(|a, b| b.anon_bytes.cmp(&a.anon_bytes).then(a.unit.cmp(&b.unit)));
    found
}

/// Data directories systemd manages for `unit` (`StateDirectory=`), if any exist.
pub fn systemd_state_paths(unit: &str) -> Vec<PathBuf> {
    let Ok(output) = Command::new("systemctl")
        .args(["show", "--property=StateDirectory", "--value", unit])
        .output()
    else {
        return Vec::new();
    };
    String::from_utf8_lossy(&output.stdout)
        .split_whitespace()
        .map(|dir| Path::new("/var/lib").join(dir))
        .filter(|path| path.is_dir())
        .collect()
}

pub fn host_name(proc_root: &Path) -> String {
    fs::read_to_string(proc_root.join("sys/kernel/hostname"))
        .ok()
        .map(|h| h.trim().to_string())
        .filter(|h| !h.is_empty())
        .unwrap_or_else(|| "vps".to_string())
}

/// Memory alert threshold: half of physical memory, or 2 GB if unknown.
pub fn memory_threshold(proc_root: &Path) -> u64 {
    fs::read_to_string(proc_root.join("meminfo"))
        .ok()
        .and_then(|t| parse_meminfo(&t))
        .and_then(|m| m.total)
        .map_or(2_000_000_000, |total| total / 2)
}

fn quote(text: &str) -> String {
    let mut out = String::from("\"");
    for c in text.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            c if c.is_control() => {
                let _ = write!(out, "\\u{:04X}", c as u32);
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

pub fn render(host_name: &str, services: &[Detected], memory_threshold: u64) -> String {
    let mut out = String::new();
    let w = &mut out;
    let _ = writeln!(
        w,
        "# Generated by `ninja-monitor --init` from the services running at install time.\n\
         # Edit freely: sudoedit /etc/ninja-monitor/config.toml, then\n\
         # sudo systemctl restart ninja-monitor. Every option is described at\n\
         # https://github.com/NinjaGoldfinch/ninja-monitor#configuration\n\
         \n\
         [server]\n\
         bind = \"127.0.0.1:9090\"\n\
         \n\
         [sampling]\n\
         interval = \"15s\"\n\
         disk_interval = \"10m\"\n\
         history = \"24h\"\n\
         \n\
         [host]\n\
         name = {}\n\
         mounts = [\"/\"]\n",
        quote(host_name)
    );

    if services.is_empty() {
        let _ = writeln!(
            w,
            "# No services were detected. Add one block per unit to watch:\n\
             # [[service]]\n\
             # name = \"app\"\n\
             # unit = \"app.service\"\n\
             # paths = [\"/var/lib/app\"]\n"
        );
    }
    for s in services {
        let paths: Vec<String> = s
            .paths
            .iter()
            .map(|p| quote(&p.display().to_string()))
            .collect();
        let _ = writeln!(
            w,
            "[[service]]\nname = {}\nunit = {}\npaths = [{}]{}\n",
            quote(s.name()),
            quote(&s.unit),
            paths.join(", "),
            if paths.is_empty() {
                "   # add data directories here to track their disk usage"
            } else {
                ""
            }
        );
    }

    let _ = writeln!(
        w,
        "[discord]\n\
         # The webhook URL lives in /etc/ninja-monitor/env (sudo ./install.sh --webhook).\n\
         enabled = true\n\
         startup_message = true\n\
         \n\
         [heartbeat]\n\
         # The URL lives in /etc/ninja-monitor/env (sudo ./install.sh --heartbeat).\n\
         enabled = false\n\
         url_env = \"NINJA_MONITOR_HEARTBEAT_URL\"\n\
         interval = \"60s\"\n\
         \n\
         [[alert]]\n\
         name = \"host memory low\"\n\
         scope = \"host\"\n\
         metric = \"mem_available_percent\"\n\
         op = \"<\"\n\
         threshold = 10\n\
         for = \"5m\"\n\
         \n\
         [[alert]]\n\
         name = \"disk filling\"\n\
         scope = \"host\"\n\
         metric = \"disk_used_percent\"\n\
         mount = \"/\"\n\
         op = \">\"\n\
         threshold = 85\n\
         for = \"10m\"\n\
         repeat = \"6h\""
    );
    for s in services {
        let name = s.name();
        let scope = quote(&format!("service:{name}"));
        let _ = writeln!(
            w,
            "\n[[alert]]\n\
             name = {}\n\
             scope = {scope}\n\
             metric = \"mem_anon_bytes\"\n\
             op = \">\"\n\
             threshold = {memory_threshold}\n\
             for = \"5m\"\n\
             \n\
             [[alert]]\n\
             name = {}\n\
             scope = {scope}\n\
             metric = \"down\"\n\
             for = \"1m\"\n\
             \n\
             [[alert]]\n\
             name = {}\n\
             scope = {scope}\n\
             metric = \"oom_kill\"",
            quote(&format!("{name} memory high")),
            quote(&format!("{name} down")),
            quote(&format!("{name} OOM kill")),
        );
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::config::Config;

    fn copy_dir(from: &Path, to: &Path) {
        fs::create_dir_all(to).unwrap();
        for entry in fs::read_dir(from).unwrap() {
            let entry = entry.unwrap();
            let target = to.join(entry.file_name());
            if entry.file_type().unwrap().is_dir() {
                copy_dir(&entry.path(), &target);
            } else {
                fs::copy(entry.path(), target).unwrap();
            }
        }
    }

    fn fixtures() -> PathBuf {
        Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures")
    }

    #[test]
    fn system_units_are_skipped() {
        for unit in [
            "systemd-journald.service",
            "cron.service",
            "getty@tty1.service",
            "ssh.service",
            "snap.lxd.daemon.service",
            "ninja-monitor.service",
        ] {
            assert!(is_system_unit(unit), "{unit}");
        }
        for unit in [
            "riot-proxy.service",
            "cloudflared.service",
            "nginx.service",
            "site.service",
        ] {
            assert!(!is_system_unit(unit), "{unit}");
        }
    }

    #[test]
    fn detects_running_services_biggest_first() {
        let tmp = tempfile::tempdir().unwrap();
        let slice = tmp.path().join("system.slice");
        copy_dir(&fixtures().join("cgroup/system.slice"), &slice);
        // An OS service, a stopped service and a non-service unit are all ignored.
        for (dir, pids) in [
            ("cron.service", "1"),
            ("stopped.service", "0"),
            ("something.mount", "1"),
        ] {
            fs::create_dir(slice.join(dir)).unwrap();
            fs::write(slice.join(dir).join("pids.current"), pids).unwrap();
        }

        let found = detect(tmp.path(), |unit| {
            if unit == "riot-proxy.service" {
                vec![PathBuf::from("/var/lib/riot-proxy")]
            } else {
                Vec::new()
            }
        });
        let units: Vec<_> = found.iter().map(|d| d.unit.as_str()).collect();
        assert_eq!(units, ["riot-proxy.service", "cloudflared.service"]);
        assert_eq!(found[0].name(), "riot-proxy");
        assert_eq!(found[0].anon_bytes, Some(208506880));
        assert_eq!(found[0].paths, [PathBuf::from("/var/lib/riot-proxy")]);
    }

    #[test]
    fn missing_cgroup_root_detects_nothing() {
        assert!(detect(Path::new("/definitely/not/here"), |_| Vec::new()).is_empty());
    }

    #[test]
    fn generated_config_is_valid() {
        let found = detect(&fixtures().join("cgroup"), |_| Vec::new());
        let text = render("my-vps", &found, memory_threshold(&fixtures().join("proc")));
        let config = Config::parse(&text).unwrap_or_else(|e| panic!("{e:#}\n{text}"));
        assert_eq!(config.host.name, "my-vps");
        assert_eq!(config.services.len(), 2);
        assert_eq!(config.services[0].unit, "riot-proxy.service");
        // Two host rules plus three per service.
        assert_eq!(config.alerts.len(), 8);
        let mem = config
            .alerts
            .iter()
            .find(|a| a.name == "riot-proxy memory high")
            .unwrap();
        assert_eq!(mem.threshold, Some((3906236u64 * 1024 / 2) as f64));
        assert!(config.discord.enabled);
        assert!(!config.heartbeat.enabled);
    }

    #[test]
    fn generated_config_without_services_is_valid() {
        let text = render("vps", &[], 2_000_000_000);
        let config = Config::parse(&text).unwrap();
        assert!(config.services.is_empty());
        assert_eq!(config.alerts.len(), 2);
    }

    #[test]
    fn odd_names_are_quoted() {
        let odd = Detected {
            unit: "we\"ird\\name@1.service".into(),
            anon_bytes: None,
            paths: vec![PathBuf::from("/var/lib/a b")],
        };
        let text = render("host \"x\"", &[odd], 1);
        let config = Config::parse(&text).unwrap_or_else(|e| panic!("{e:#}\n{text}"));
        assert_eq!(config.host.name, "host \"x\"");
        assert_eq!(config.services[0].name, "we\"ird\\name@1");
        assert_eq!(config.services[0].paths, [PathBuf::from("/var/lib/a b")]);
    }

    #[test]
    fn host_name_and_threshold_fallbacks() {
        assert_eq!(host_name(Path::new("/definitely/not/here")), "vps");
        assert_eq!(
            memory_threshold(Path::new("/definitely/not/here")),
            2_000_000_000
        );
    }
}
